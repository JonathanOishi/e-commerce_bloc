class Product {
  final String id;
  final String title;
  final String description;
  final double price;
  final double discount;
  final int qty;
  final String imgUrl;

  Product({
    required this.id,
    required this.title,
    required this.description,
    required this.price,
    required this.discount,
    required this.qty,
    required this.imgUrl,
  });
}
